// Runs headless scenarios through the REAL CLI (headless_cmd from game.contract.json),
// checks expectations, checks determinism, and writes evidence to docs/proof/<phase>/.
// Usage: npm run proof [-- phase-1]     Exit code != 0 if any expectation fails.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import os from 'node:os';

const phase = process.argv[2] || 'phase-1';
const dir = `docs/proof/${phase}`;
mkdirSync(`${dir}/runs`, { recursive: true });
const contract = JSON.parse(readFileSync('game.contract.json', 'utf8'));
const [cmd, ...pre] = contract.headless_cmd.split(' ');
const S = 'tests/scenarios';

// id -> requirement, CLI args, expectation on the end line + required events
const cases = [
  { id: 'P1-win', req: 'Playable from start to WIN on default Night 1 (bot-recorded inputs)', args: ['--seed', '1', '--inputs', `${S}/win-seed1.inputs.json`, '--ticks', '18000', '--snapshot-every', '60'], expect: { state: 'won' }, events: ['mote_picked', 'deposit', 'lantern_lit', 'game_over'] },
  { id: 'P1-idle-lose', req: 'Shades chase + hit; LOSE when flames run out (no input, default Night 1)', args: ['--seed', '1', '--ticks', '18000', '--snapshot-every', '60'], expect: { state: 'lost' }, events: ['player_hit', 'game_over'] },
  { id: 'P1-dawn', req: 'LOSE at dawn when time runs out', args: ['--seed', '1', '--scenario', `${S}/dawn.scenario.json`, '--ticks', '18000', '--snapshot-every', '60'], expect: { state: 'lost', ticks: 300 }, events: ['game_over'] },
  { id: 'P1-lantern', req: 'Pick 5 motes along +Z, deposit at L1, lantern lights', args: ['--seed', '1', '--scenario', `${S}/lantern-run.scenario.json`, '--inputs', `${S}/lantern-run.inputs.json`, '--ticks', '240', '--snapshot-every', '30'], expect: { state: 'playing', score: 5 * contract.tuning.score.per_mote + contract.tuning.score.per_lantern }, events: ['mote_picked', 'deposit', 'lantern_lit'] },
  { id: 'P1-contract-example', req: 'Example scenario + inputs from Test Contract v1.0 run cleanly', args: ['--seed', '1', '--scenario', `${S}/contract-example.scenario.json`, '--inputs', `${S}/contract-example.inputs.json`, '--ticks', '300'], expect: { state: 'playing' }, events: ['mote_picked'] },
];

const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);
const rows = [];
let failed = 0;
for (const c of cases) {
  const out = `${dir}/runs/${c.id}.jsonl`;
  const args = [...pre, ...c.args, '--night', '1', '--out', out];
  const t0 = process.hrtime.bigint();
  const r = spawnSync(cmd, args, { encoding: 'utf8' });
  const ms = Number(process.hrtime.bigint() - t0) / 1e6;
  const text = r.status === 0 ? readFileSync(out, 'utf8') : '';
  // determinism: run again to a temp file and compare bytes
  const out2 = `${os.tmpdir()}/ddl-${c.id}.jsonl`;
  spawnSync(cmd, [...pre, ...c.args, '--night', '1', '--out', out2], { encoding: 'utf8' });
  const text2 = r.status === 0 ? readFileSync(out2, 'utf8') : 'x';
  const lines = text.trim().split('\n').filter(Boolean).map((l) => JSON.parse(l));
  const end = lines.at(-1) || {};
  const names = new Set(lines.filter((l) => l.type === 'event').map((l) => l.name));
  const go = lines.find((l) => l.name === 'game_over');
  const problems = [];
  if (r.status !== 0) problems.push(`exit ${r.status}: ${r.stderr.trim()}`);
  for (const [k, v] of Object.entries(c.expect)) if (end[k] !== v) problems.push(`end.${k}=${end[k]} (want ${v})`);
  for (const e of c.events) if (!names.has(e)) problems.push(`missing event ${e}`);
  if (text !== text2) problems.push('NOT deterministic');
  if (problems.length) failed++;
  rows.push({ ...c, ok: !problems.length, problems, end, go: go ? `${go.data.result}/${go.data.reason} @${go.tick}` : '-', det: text === text2, hash: sha(text), ms, cmd: [cmd, ...args].join(' ') });
}

const md = [
  `# Headless evidence — ${phase}`,
  '',
  `Generated by \`npm run proof\` (scripts/proof.js). Commit: \`${spawnSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).stdout.trim() || 'uncommitted'}\`. Machine: ${os.cpus()[0]?.model.trim()} · ${os.platform()} ${os.release()} · Node ${process.version}.`,
  '',
  'Each run uses the real `headless_cmd` from game.contract.json and is executed **twice**; outputs must be byte-identical (determinism).',
  '',
  '| ID | Requirement | Result | End line | game_over | Deterministic | sha256[0:16] | Time |',
  '|---|---|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${r.req} | ${r.ok ? 'PASS' : 'FAIL: ' + r.problems.join('; ')} | \`${JSON.stringify(r.end)}\` | ${r.go} | ${r.det ? 'yes' : 'NO'} | \`${r.hash}\` | ${r.ms.toFixed(0)} ms |`),
  '',
  '## Commands',
  '',
  ...rows.map((r) => `- **${r.id}**: \`${r.cmd}\` → [runs/${r.id}.jsonl](runs/${r.id}.jsonl)`),
  '',
].join('\n');
writeFileSync(`${dir}/headless-evidence.md`, md);
console.log(md);
process.exitCode = failed ? 1 : 0;
